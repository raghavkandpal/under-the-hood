// Seeded pseudo-random numbers, so demos and tests are reproducible. No DOM.

/** mulberry32: returns a function giving floats in [0, 1). */
export function mulberry(seed) { return () => { seed |= 0; seed = (seed + 0x6d2b79f5) | 0; let t = Math.imul(seed ^ (seed >>> 15), 1 | seed); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
/** A standard normal draw (Box–Muller) from a uniform source like mulberry. */
export function gaussian(rnd) { let u = 0; while (!u) u = rnd(); return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * rnd()); }
