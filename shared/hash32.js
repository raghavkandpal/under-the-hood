// A fast non-cryptographic string hash for sketches and demos. Used by hyperloglog and count-min-sketch.

/** 32-bit hash: FNV-1a, then murmur3's finaliser so every bit is well mixed. */
export function hash(s) {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 0x01000193);
  h ^= h >>> 16; h = Math.imul(h, 0x85ebca6b); h ^= h >>> 13; h = Math.imul(h, 0xc2b2ae35); h ^= h >>> 16;
  return h >>> 0;
}
